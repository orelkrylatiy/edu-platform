import { test, expect } from "@playwright/test";
import { loginAsOwner } from "./helpers.js";

test.beforeEach(async ({ page }) => { await loginAsOwner(page); });

test("course, notes, timer, theme and mobile navigation", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Учёба — это/ })).toBeVisible();
  await page.screenshot({ path: "test-results/dashboard-desktop.png", fullPage: true });
  await page.locator(".hero").getByRole("button", { name: "Продолжить" }).click();
  await expect(page.getByRole("heading", { name: /диагностика/i })).toBeVisible();
  const checkbox = page.getByRole("checkbox").first();
  await checkbox.check();
  await expect(checkbox).toBeEnabled();
  await expect(checkbox).toBeChecked();
  const note = page.getByRole("textbox", { name: "Мысли, выводы, вопросы" });
  await note.fill("My persistent note");
  await expect(page.locator(".note-card").getByText("Сохранено", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: /Учёба — это/ })).toBeVisible();
  await page.getByRole("button", { name: /01.*диагностика/i }).click();
  await expect(page.getByRole("checkbox").first()).toBeChecked();
  await expect(page.getByRole("textbox", { name: "Мысли, выводы, вопросы" })).toHaveValue("My persistent note");
  await page.getByRole("button", { name: "Сменить тему" }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
  await page.getByRole("button", { name: "Сменить тему" }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.locator(".lesson-top").getByRole("button", { name: "AI mentor" }).click();
  await expect(page.locator(".chat")).toBeVisible();
  await expect(page.locator(".context")).toContainText(/диагностика/i);
  await page.screenshot({ path: "test-results/lesson-dark.png", fullPage: true });
  await page.getByRole("button", { name: "Close chat" }).click();
  await page.getByRole("button", { name: "Фокус", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Меньше шума/ })).toBeVisible();
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(page.getByRole("button", { name: "Pause", exact: true })).toBeVisible();
  await page.waitForTimeout(1500);
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await page.getByRole("button", { name: "Save session and reset" }).click();
  await expect(page.locator(".focus-time")).toHaveText("25:00");
  await page.getByRole("button", { name: "Активность" }).click();
  await expect(page.getByRole("heading", { name: "Активность" })).toBeVisible();
  await expect(page.locator(".active-day")).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(page.getByRole("heading", { name: /Учёба — это/ })).toBeVisible();
  await expect(page.locator(".sidebar")).toHaveCount(0);
  await page.getByRole("button", { name: "Навигация" }).click();
  await expect(page.locator(".sidebar")).toBeVisible();
  await page.getByRole("button", { name: "Collapse navigation" }).click();
  await expect(page.locator(".sidebar")).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/dashboard-mobile.png", fullPage: true });
});


test("mentor panels resize, collapse and start isolated chat sessions", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  await page.locator(".hero").getByRole("button", { name: "Продолжить" }).click();
  await page.getByRole("button", { name: "Открыть AI-чат" }).click();
  const chat = page.locator(".chat");
  await expect(chat).toBeVisible();
  const chatHandle = page.getByRole("separator", { name: "Ширина чата" });
  const navHandle = page.getByRole("separator", { name: "Ширина навигации" });
  const before = (await chat.boundingBox()).width;
  await chatHandle.focus();
  await chatHandle.press("ArrowLeft");
  expect((await chat.boundingBox()).width).toBeGreaterThan(before);
  const dragStart = await chatHandle.boundingBox();
  const widthBeforeDrag = (await chat.boundingBox()).width;
  await page.mouse.move(dragStart.x + dragStart.width / 2, dragStart.y + 100);
  await page.mouse.down();
  await page.mouse.move(dragStart.x - 40, dragStart.y + 100, { steps: 5 });
  await page.mouse.up();
  expect((await chat.boundingBox()).width).toBeGreaterThan(widthBeforeDrag);
  const navBefore = (await page.locator(".sidebar").boundingBox()).width;
  await navHandle.focus();
  await navHandle.press("ArrowRight");
  expect((await page.locator(".sidebar").boundingBox()).width).toBeGreaterThan(navBefore);
  await page.getByRole("button", { name: "Интервью", exact: true }).hover();
  await expect(page.getByRole("tooltip")).toContainText("без подсказок");
  await page.getByRole("button", { name: "Интервью", exact: true }).click();
  const requests = [];
  await page.route("**/api/chat", async (route) => {
    const body = route.request().postDataJSON();
    requests.push(body);
    await route.fulfill({ json: { messages: [{ role: "user", content: body.text }, { role: "assistant", content: "Ответ" }] } });
  });
  const input = chat.getByRole("textbox", { name: "Message" });
  await input.fill("Первый вопрос");
  await chat.getByRole("button", { name: "Отправить" }).click();
  await expect(chat.getByText("Первый вопрос", { exact: true })).toBeVisible();
  await chat.getByRole("button", { name: "+ Новый чат", exact: true }).click();
  await expect(chat.getByText("Первый вопрос", { exact: true })).toHaveCount(0);
  await input.fill("Второй вопрос");
  const sessions = chat.getByRole("combobox", { name: "Сессия чата" });
  const draftSession = await sessions.inputValue();
  await chat.getByRole("button", { name: "+ Новый чат", exact: true }).click();
  await expect(input).toHaveValue("");
  await sessions.selectOption(draftSession);
  await expect(input).toHaveValue("Второй вопрос");
  await chat.getByRole("button", { name: "Отправить" }).click();
  await expect(chat.getByText("Второй вопрос", { exact: true })).toBeVisible();
  expect(requests[0].session_id).toBeNull();
  expect(requests[1].session_id).toMatch(/^[a-f0-9-]{36}$/);
  await chat.getByRole("combobox", { name: "Сессия чата" }).selectOption("");
  await expect(chat.getByText("Первый вопрос", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Свернуть AI-чат" }).click();
  await expect(chat).toHaveCount(0);
  await page.getByRole("button", { name: "Открыть AI-чат" }).click();
  await expect(chat.getByText("Первый вопрос", { exact: true })).toBeVisible();
  const savedChatWidth = (await chat.boundingBox()).width;
  const savedNavWidth = (await page.locator(".sidebar").boundingBox()).width;
  await page.reload();
  await page.getByRole("button", { name: "Открыть AI-чат" }).click();
  expect((await chat.boundingBox()).width).toBe(savedChatWidth);
  expect((await page.locator(".sidebar").boundingBox()).width).toBe(savedNavWidth);
});
